function displayMovies(data){
  
  //თუ movieGrid ვერ მოიძებნა: ფუნქცია შეჩერდება და error არ გამოვა
  if(!movieGrid) return;

  //ძველ ფილმებს შლის ეკრანიდან
  movieGrid.innerHTML = "";

  //ქმნის ცარიელ ტექსტს, ინახება HTML კოდი 
  let html = "";

  //ეწებს და გადადის ყველა ფილმზე თითო-თითო 
  data.forEach(movie => {

    // სტრინგ-ში ამადებს კოდს
    // ქმნის ფილმის ბარათს,
    // აჩვენებს ფილმის სურათს;image → ფოტო,title → alt ტექსტი
    // ფილმის ინფორმაციის ბლოკი
    // ფილმის სახელი
    // ფილმის წელი
    // button ღილაკი ფილმის სანახავად
    // შენახვის ღილაკი
    // ბოლო ყველა ფილმი ეკრანში გამოდის
    
    
    
    html += `

    <div class="card">

      <img src="${movie.image}" alt="${movie.title}">
      
      <div class="movie-info">

        <h3>${movie.title}</h3>

        <p>${movie.year}</p>

        
        <button 
        class="watch-btn"
        onclick="watchMovie('${movie.video}')"
        >
          Watch Movie
        </button>

      
        <button
          class="save-btn"
          onclick='saveMovie(${JSON.stringify(movie)})'
        >
          Save Movie
        </button>

      </div>

    </div>

    `;

  });

  movieGrid.innerHTML = html;


}



