// ფილმების შენახვის ფუნქცია
function saveMovie(movie){

  /*ამოწმებს უკვე არის თუ არა ფილმი შენახული
    თუ იგივე title აქვს → უკვე არსებობს*/

  const exists = savedMovies.some(
    item => item.title === movie.title

  );

  /*თუ არ არის შეინახებს */
  if(!exists){

    savedMovies.push(movie);  /*სიაში ამადებს */

    localStorage.setItem(   /*ინახავს ბრაუზერში */

      "savedMovies",

      JSON.stringify(savedMovies)

    );

    alert(movie.title + " saved!");  /* შეტყობინება გამოდის :შენახულიუა */

  } else {

    alert("Movie already saved!");  /*თუ არსებობს გაფრთხილდა  */

  }

}



