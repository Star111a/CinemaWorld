// წებნის ფუნქცია 

function searchMovies(){

/* იღებს იმას, რაც მომხმარებელმა დაწერა
value → input-ის ტექსტი
toLowerCase() → პატარა ასოებად აქცევს*/
  
let input =
  document.getElementById("search")
  .value
  .toLowerCase();

  /*პოულობს ყველა ფილმის ბარათს */
  let cards =
  document.querySelectorAll(".card");

  /* ფილმის ყველა ბარათს შეამოწმებს */
  cards.forEach(card => {

    /*იღებს ფილმის სახელს */
    let title =
    card.querySelector("h3")
    .innerText
    .toLowerCase();
   
    /* მთავარი ლოგიკა:
     თუ title შეიცავს input-ს - გამოჩნდეს 
     თუ არა - დაიმალოს*/
    card.style.display =
    title.includes(input)
    ? "block"
    : "none";

  });

}



